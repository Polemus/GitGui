#!/usr/bin/env bash
#
# Emits the copy of the manifest that Flathub builds from, into
#   dist/flathub/
#
# Usage: build/linux/flatpak/flathub-manifest.sh <version> [--ref <git-ref>]
#   --ref  what to pin to, if not the v<version> tag
#
# Flathub clones the source itself, so its manifest cannot use the `type: dir`
# source that makes a local checkout build. This produces the same manifest with
# that one source swapped for a git source pinned to a tag and a commit, and
# copies the NuGet lists next to it.
#
# Generating it rather than keeping a second manifest checked in is the point:
# the two would drift, and the way you would find out is a Flathub build behaving
# differently from the one you tested.
#
# The result goes in the flathub/io.github.polemus.GitGui repository. See
# docs/flatpak.md for what to do with it.
set -euo pipefail

APP_ID=io.github.polemus.GitGui
VERSION="${1:?usage: flathub-manifest.sh <version> [--ref <git-ref>]}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
HERE="$ROOT/build/linux/flatpak"
OUT="$ROOT/dist/flathub"

REF="v$VERSION"
if [ "${2:-}" = "--ref" ]; then
    REF="${3:?--ref needs a git ref}"
fi

URL="$(git -C "$ROOT" remote get-url origin | sed 's/\.git$//').git"

if ! COMMIT="$(git -C "$ROOT" rev-parse --verify "$REF^{commit}" 2>/dev/null)"; then
    echo "!! $REF is not a commit in this repository" >&2
    echo "   tag the release first, or pass --ref <branch-or-sha>" >&2
    exit 1
fi

# Flathub builds whatever the commit contains, so a manifest pinned to a commit
# that is only on this machine produces a build nobody else can reproduce.
if ! git -C "$ROOT" branch -r --contains "$COMMIT" 2>/dev/null | grep -q . \
   && ! git -C "$ROOT" ls-remote --tags origin "$REF" 2>/dev/null | grep -q .; then
    echo "!! $REF ($COMMIT) has not been pushed - Flathub would not be able to fetch it" >&2
    exit 1
fi

echo "==> $APP_ID $VERSION from $REF ($COMMIT)"
mkdir -p "$OUT"

# Replace the source block that begins "- type: dir" with a git source. The
# block runs until the first line indented less than its own keys, which is the
# comment introducing the nuget-sources entries.
{
    echo "# Generated by build/linux/flatpak/flathub-manifest.sh from"
    echo "# build/linux/flatpak/$APP_ID.yml in $URL"
    echo "# Do not edit this copy: edit that one and generate this again."
    echo "#"
} > "$OUT/$APP_ID.yml"

awk -v url="$URL" -v tag="$REF" -v commit="$COMMIT" '
    /^      - type: dir$/ {
        print "      # Rewritten from the `type: dir` source in the manifest this was"
        print "      # generated from, by build/linux/flatpak/flathub-manifest.sh."
        print "      - type: git"
        print "        url: " url
        print "        tag: " tag
        print "        commit: " commit
        skipping = 1
        next
    }
    skipping {
        # Blank lines belong to whichever block comes next, so they do not end this one.
        if ($0 ~ /^[[:space:]]*$/) next
        if (match($0, /^ */) && RLENGTH >= 8) next
        skipping = 0
    }
    { print }
' "$HERE/$APP_ID.yml" >> "$OUT/$APP_ID.yml"

if grep -qE '^ +- type: dir' "$OUT/$APP_ID.yml"; then
    echo "!! the dir source is still in the output - the manifest layout changed" >&2
    exit 1
fi
if ! grep -q "commit: $COMMIT" "$OUT/$APP_ID.yml"; then
    echo "!! the git source did not make it into the output" >&2
    exit 1
fi

cp "$HERE/nuget-sources-x86_64.json" "$HERE/nuget-sources-aarch64.json" "$OUT/"

echo "==> Wrote:"
ls -la "$OUT"
echo
echo "Copy these into the flathub/$APP_ID repository and open a pull request."
